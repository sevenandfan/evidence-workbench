"""Extract a fixed author table into JSON; never rewrite the workbooks."""
import hashlib
import json
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / ".tools/xls-reader"))
import openpyxl
import xlrd

COMMIT = "7a1334c053201ccdd2054417f74aa3d62776dd03"
UPSTREAM = ROOT / "data/manylabs1/upstream" / COMMIT
DEST = ROOT / "data/manylabs1/sunk-costs-v1"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    source = json.loads((UPSTREAM / "source_manifest.json").read_text(encoding="utf-8"))
    before = {}
    for name, record in source["files"].items():
        before[name] = digest((UPSTREAM / name).read_bytes())
        if before[name] != record["sha256"]:
            raise ValueError("Upstream hash mismatch: " + name)
    # Unknown workbook extension affects editing support only. This is read-only;
    # nothing is exported, so all original source bytes remain intact.
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="Unknown extension is not supported")
        book = openpyxl.load_workbook(UPSTREAM / "MLforR.xlsx", data_only=True, read_only=True)
        sheet = book["Sunk Costs"]
        rows = list(sheet.iter_rows(values_only=True))
        if rows[0][:8] != ("Site", "N (Paid)", "N (Free)", "N (Excluded or no response)", "Mean (Paid)", "Mean (Free)", "SD (Paid)", "SD (Free)"):
            raise ValueError("Unexpected author input headers")
        samples = []
        for idx, row in enumerate(rows[1:], 2):
            if row[0] == "Mean across samples:":
                continue
            if any(type(row[k]) not in (int, float) or row[k] != int(row[k]) for k in (1, 2, 3)):
                raise ValueError("Noninteger sample/exclusion count in source table")
            samples.append({"site": row[0], "n_paid": int(row[1]), "n_free": int(row[2]), "excluded_or_no_response": int(row[3]), "mean_paid": row[4], "mean_free": row[5], "sd_paid": row[6], "sd_free": row[7], "source_range": f"'Sunk Costs'!A{idx}:H{idx}"})
        book.close()
    book = xlrd.open_workbook(str(UPSTREAM / "ML_ESCIfromR.xls"))
    ref = book.sheet_by_name("ESCIfromR")
    expected_header = [".id", "id1", "id2", "Lower.Conf.Limit.smd", "smd", "Upper.Conf.Limit.smd"]
    if ref.row_values(0)[1:7] != expected_header:
        raise ValueError("Unexpected author reference headers")
    gold = []
    for idx in range(1, ref.nrows):
        row = ref.row_values(idx)
        if row[1] == "study1" and row[2] != "Mean across samples:":
            gold.append({"site": row[2], "effect": row[5], "ci_low": row[4], "ci_high": row[6], "source_range": f"'ESCIfromR'!B{idx+1}:G{idx+1}"})
    if len(samples) != 37 or len(gold) != 37 or {r["site"] for r in samples} != {r["site"] for r in gold}:
        raise ValueError("Expected 36 sites + Overall, with complete external gold")
    dataset = {"schema_version": "manylabs_summary_v1", "study": "Sunk Costs", "synthetic": False, "level": "author_aggregate", "upstream_commit": COMMIT, "samples": samples}
    reference = {"schema_version": "manylabs_gold_v1", "origin": "Author-published R output, not generated by our workflow", "upstream_commit": COMMIT, "rows": gold}
    dataset_bytes = json.dumps(dataset, indent=2, allow_nan=False).encode()
    gold_bytes = json.dumps(reference, indent=2, allow_nan=False).encode()
    plan = {"schema_version": "manylabs_plan_v1", "method": "author_smd_nct", "contrast": "Paid minus Free", "dataset_sha256": digest(dataset_bytes), "gold_sha256": digest(gold_bytes), "effect_tolerance": 1e-7, "ci_tolerance": 1e-6, "confidence_rule": "n_total > 1000 => 0.99; else 0.95", "excluded_summary_rows": ["Mean across samples:"], "upstream": source}
    artifacts = {"dataset.json": dataset_bytes, "gold.json": gold_bytes, "plan.json": json.dumps(plan, indent=2).encode()}
    DEST.mkdir(parents=True, exist_ok=True)
    for name, raw in artifacts.items():
        target = DEST / name
        if target.exists() and target.read_bytes() != raw:
            raise ValueError("Prepared slice changed; create a new version rather than overwrite: " + name)
        if not target.exists():
            target.write_bytes(raw)
    for name, expected in before.items():
        if digest((UPSTREAM / name).read_bytes()) != expected:
            raise ValueError("Upstream input changed")
    print("Prepared", len(samples), "summary rows at", DEST)
    print("Participant n (Overall):", samples[0]["n_paid"] + samples[0]["n_free"])


if __name__ == "__main__":
    main()
